/*
Q1 – Above-Average Product Sales Analysis
Objective: Identify products whose total sales are greater than the average total sales generated per product.
Requirements
1. Calculate the total sales generated by each product using product_id and product_name.
2. Calculate the average total sales across all products.
   - First, calculate the total sales separately for each product.
   - Then calculate the average of those product-level totals.
   - Do not calculate the average of individual sales records.
3. Identify products whose total sales are strictly greater than the average product-level sales.
4. For each qualifying product, display:
   - product_id
   - product_name
   - category
   - total_sales
   - distinct_orders (number of unique orders containing that product)
5. Sort the results by total_sales in descending order.
Expected output
Product ID	Product name	Category	Total sales	Distinct orders
...	...	...	...	...

SQL concepts
- GROUP BY
- SUM()
- COUNT(DISTINCT)
- Subqueries
- HAVING or an outer WHERE filter
- ORDER BY
Important: The average must be calculated using product-level total sales. This distinction is central to the question.
*/

SELECT
    product_id,
    product_name,
    category,
    SUM(sales) AS total_sales,
    COUNT(DISTINCT order_id) AS distinct_orders
FROM "project_1_super_store_sales_dataset"
GROUP BY product_id, product_name, category
HAVING SUM(sales) > (
    SELECT
        AVG(total_sales_per_product) AS avg_of_total_sales_per_product
    FROM (
        SELECT
            SUM(sales) AS total_sales_per_product
        FROM "project_1_super_store_sales_dataset"
        GROUP BY product_id, product_name
    ) AS product_summary
)
ORDER BY total_sales DESC;


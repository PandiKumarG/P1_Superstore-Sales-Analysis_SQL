CREATE TABLE segment_targets_temp (
    segment VARCHAR(30) Primary Key, 
    sales_target NUMERIC(12,2)
)

INSERT INTO segment_targets_temp(segment, sales_target)
VALUES
    ('Consumer', 500000),
    ('Corporate', 300000),
    ('Home Office', 200000)

SELECT
    t1.segment,
    COUNT(DISTINCT customer_id) AS distinct_customers,
    COUNT(DISTINCT order_id) AS distinct_order,
    t2.sales_target AS sales_target,
    SUM(t1.sales) AS total_sales,
    ((SUM(t1.sales) / t2.sales_target) * 100) AS achievement_percentage,

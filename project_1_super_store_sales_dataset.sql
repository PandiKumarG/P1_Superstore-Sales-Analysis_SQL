ORDER BY achievement_percentage DESC;

/*
Q3 – Product Sales Ranking Within Each Category.
Objective
Identify the top three products by total sales within each product category.
Requirements
1. Calculate total sales for each product using product_id, product_name, and category.
2. Rank products within each category based on total sales in descending order.
3. Use DENSE_RANK() so products with equal sales receive the same rank, without skipping the next rank.
4. Display only the top three ranks from each category.
5. Include these columns:
   - category
   - product_id
   - product_name
   - total_sales
   - sales_rank
6. Sort the final output by category and sales_rank.
Expected SQL concepts: GROUP BY, SUM(), DENSE_RANK(), PARTITION BY, and a CTE or subquery to filter the ranked results.
*/

WITH sales_rank_calc AS (
    SELECT
        category,
        product_id,
        product_name,
        SUM(sales) AS total_sales,
        DENSE_RANK() OVER (
            PARTITION BY category
            ORDER BY SUM(sales) DESC
        ) AS sales_rank
    FROM "project_1_super_store_sales_dataset"
    GROUP BY category, product_id, product_name
)

SELECT
    category,
    product_id,
    product_name,
    total_sales,
    sales_rank
FROM sales_rank_calc
WHERE sales_rank <= 3
ORDER BY category ASC, sales_rank ASC;

/*
Q4 – Monthly Sales Trend Analysis.
Current-level practice
Objective
Analyze monthly sales performance and identify how sales change compared with the previous month.
Requirements
1. Calculate total sales for each month using order_date.
2. Display the month in YYYY-MM format.
3. Calculate the previous month's sales using LAG().
4. Calculate the month-over-month (MoM) sales change:
\[
\text{MoM Change} = \text{Current Month Sales} - \text{Previous Month Sales}
\]

5. Classify the sales trend using CASE WHEN:
- Positive change → Growth
- Negative change → Decline
- Zero change → No Change
- No previous-month value → First Month
6. Include these output columns:
- sales_month
- total_sales
- previous_month_sales
- mom_sales_change
- sales_trend
7. Sort chronologically by month.
CTE requirement
Use at least three meaningful chained CTEs:
- CTE 1: Calculate monthly sales.
- CTE 2: Calculate previous month's sales using LAG().
- CTE 3: Calculate MoM sales change.
- Final SELECT: Apply the CASE WHEN classification and display the required columns.
Expected concepts: GROUP BY, date functions, TO_CHAR(), LAG(), CTEs, arithmetic calculations, and CASE WHEN.
*/

WITH monthly_sales_calc AS (
    SELECT
        EXTRACT(YEAR FROM order_date) AS sales_year,
        EXTRACT(MONTH FROM order_date) AS Sales_month,
        SUM(sales) AS current_month_sales
    FROM "project_1_super_store_sales_dataset"
    GROUP BY EXTRACT(YEAR FROM order_date), EXTRACT(MONTH FROM order_date)
),

previous_month_sales_calc AS  (
    SELECT 
        sales_year,
        Sales_month,
        LAG(current_month_sales) OVER (
            ORDER BY sales_year, Sales_month
        ) AS previous_month_sales,
        current_month_sales
    FROM monthly_sales_calc
),

month_over_month_sales_calc AS (
    SELECT
        sales_year,
        Sales_month,
        previous_month_sales,
        current_month_sales AS total_sales,
        (current_month_sales - previous_month_sales) AS mom_sales_change
    FROM previous_month_sales_calc
)

SELECT
    CONCAT(sales_year,'-',LPAD(Sales_month::TEXT, 2, '0')) AS sales_month,
    previous_month_sales,
    total_sales,    
    mom_sales_change,
    CASE 
        WHEN mom_sales_change > 0 THEN 'Growth'
        WHEN mom_sales_change < 0 THEN 'Decline'
        WHEN mom_sales_change = 0 THEN 'No Change'
        ELSE 'First Month'
    END AS sales_trend
FROM month_over_month_sales_calc
ORDER BY sales_year ASC, sales_month ASC;

/*
Q5 – Customer Order Frequency Analysis
Objective
Analyze how frequently customers place orders by calculating the number of days between their consecutive orders.
Requirements
1. First, retrieve unique customer-order combinations using SELECT DISTINCT with:
- customer_id
- customer_name
- order_id
- order_date
Why? One order can contain multiple products and therefore appear in multiple dataset rows. We want each order to appear only once.

2. Use LAG() to retrieve the previous order date for each customer.
- Use PARTITION BY customer_id.
- Order the records by order_date.
3. Calculate the number of days between the current order date and the previous order date.

4. Extract the following from the current order date:
- Order year
- Order month
5. Classify the order sequence using CASE WHEN:
- Previous order date is NULL → First Order
- Otherwise → Repeat Order
Expected output columns
Column	Description
customer_id	Customer identifier
customer_name	Customer name
order_id	Unique order identifier
order_date	Current order date
previous_order_date	Previous order date
days_since_previous_order	Days between consecutive orders
order_year	Year of current order
order_month	Month of current order
order_sequence	First Order / Repeat Order

Expected SQL concepts
- SELECT DISTINCT
- CTEs
- LAG()
- PARTITION BY
- ORDER BY
- Date subtraction
- EXTRACT()
- CASE WHEN
Important clarification: We are analyzing at the customer-order level, not the product level. Therefore, we will not use product_name, and GROUP BY is not required.
*/

WITH data_setup AS (
    SELECT
        customer_id,
        customer_name,
        order_id,
        order_date
    FROM "project_1_super_store_sales_dataset"
    GROUP BY customer_id, customer_name, order_id, order_date
),

calculations AS  (
    SELECT 
        customer_id,
        customer_name,
        order_id,
        order_date,
        LAG(order_date) OVER (
            PARTITION BY customer_id 
            ORDER BY order_date ASC
        ) AS previous_order_date,
        EXTRACT(YEAR FROM order_date) AS order_year,
        EXTRACT(MONTH FROM order_date) AS order_month
    FROM data_setup
)

SELECT
    customer_id,
    customer_name,
    order_id,
    previous_order_date,
    order_date,
    (order_date - previous_order_date) AS days_since_previous_order,
    order_year,
    order_month,
    CASE 
        WHEN previous_order_date IS NULL THEN 'First Order'
        ELSE 'Repeat Order'
    END AS order_sequence
FROM calculations
ORDER BY customer_id, order_date, order_id

/*
Q6 – Customer Purchase Behavior Analysis
Mixed concepts · Current level
Objective
Identify customers who have generated above-average sales within their respective segments and analyze their purchasing activity.
Requirements
1. Calculate total sales for each customer within each segment.
2. Calculate the average customer-level sales within each segment.
   - Important: Calculate the average of customer-level sales, not the average of individual transaction sales.
3. Identify customers whose total sales are strictly greater than their segment's average customer sales.
4. For these customers, calculate their distinct order count.
5. Rank the qualifying customers within each segment based on total sales in descending order using RANK().
6. Classify customers based on their order count:
   - 10 or more orders → Frequent Customer
   - Fewer than 10 orders → Occasional Customer
Expected output columns
Column	Description
segment	Customer segment
customer_id	Customer identifier
customer_name	Customer name
total_sales	Total customer sales
average_segment_customer_sales	Average customer sales within the segment
distinct_orders	Number of distinct orders
sales_rank	Rank within the segment
customer_type	Frequent / Occasional

Expected SQL concepts
- CTEs
- GROUP BY
- AVG()
- Subquery or window function
- RANK()
- COUNT(DISTINCT)
- CASE WHEN
Important: The average must be calculated using customer-level totals grouped by segment. Don't calculate it directly from the original sales records.

Try solving it independently. I'll review it against these exact requirements.
*/

WITH sales_rank_calc AS (
SELECT 
    t1.customer_id AS customer_id, 
    t1.customer_name AS customer_name, 
    t1.segment AS segment,
    SUM(sales) AS total_sales_per_segment_per_customer,
    COUNT(DISTINCT order_id) AS distinct_orders,
    RANK() OVER (
        PARTITION BY t1.segment
        ORDER BY SUM(sales) DESC
    ) AS sales_rank
FROM "project_1_super_store_sales_dataset" AS t1
GROUP BY customer_id, customer_name, segment
HAVING SUM(sales) > (
    SELECT
        AVG(customer_total)
    FROM (
        SELECT 
            SUM(sales) AS customer_total
        FROM "project_1_super_store_sales_dataset" AS t2
        WHERE t2.segment = t1.segment
        GROUP BY t2.customer_id
    ) AS customer_sales
    )
)

SELECT
    customer_id,
    customer_name, 
    segment,  
    total_sales_per_segment_per_customer,
    distinct_orders,
    sales_rank,
    CASE 
        WHEN distinct_orders >= 10 THEN 'Frequent Customer'
        ELSE 'Occasional Customer'
    END AS customer_type
FROM sales_rank_calc
ORDER BY segment, sales_rank